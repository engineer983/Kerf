#[test]
fn part_files_from_two_on_say_fit_the_bit_and_set_z() {
    let program = generate(&square(), &two_bits()).unwrap();
    let first = program.part_file(0).unwrap();
    let second = program.part_file(1).unwrap();
    let header = format!("; Generated by Kerf {VERSION}\n");
    assert!(first.starts_with(&header));
    assert!(!first.contains("before running this file"));
    assert!(
        first.contains("; Next: fit T2 (1 mm tapered ball nose), set Z again, then run part 2.")
    );
    assert!(second.starts_with(&header));
    assert!(second.contains(
        "; Fit T2 (1 mm tapered ball nose) and set Z before running this file.\nG17 G21 G90 G94 G54\n"
    ));
    // A file of its own has no change block: it just ends.
    assert!(!first.contains("G4 P0.1"));
    assert!(program.part_file(2).is_err());
}

#[test]
fn every_part_file_ends_with_m5() {
    let mut job = two_bits();
    job.machine.end_gcode = "M30".into();
    job.machine.start_gcode = "G0 Z30".into();
    let program = generate(&square(), &job).unwrap();
    let first = program.part_file(0).unwrap();
    let lines = code(&first);
    assert_eq!(
        lines[lines.len() - 5..],
        ["M5", "G4 P5", "G0 Z20", "G0 X0 Y0", "M30"]
    );
    let second = program.part_file(1).unwrap();
    let lines = code(&second);
    assert_eq!(lines[lines.len() - 3..], ["M5", "G0 X0 Y0", "M30"]);
    // Both start as a whole job does, with the machine's start lines.
    for file in [&first, &second] {
        assert_eq!(code(file)[..2], ["G0 Z30", "G17 G21 G90 G94 G54"]);
        assert_eq!(file.matches("M30").count(), 1);
    }
}

#[test]
fn m6_file_lists_every_change_and_says_set_z_before_each_m6() {
    let job = job(vec![
        profile(Some(bit(1, "6 mm flat end mill", 6.0)), 5.0),
        profile(Some(bit(2, "1 mm tapered ball nose", 1.0)), 5.0),
        profile(Some(bit(3, "3 mm flat end mill", 3.0)), 5.0),
    ]);
    let program = generate(&square(), &job).unwrap();
    let file = program.with_m6().unwrap();
    assert!(file.contains("; This job changes bits 2 times: T1 6 mm flat end mill, T2 1 mm tapered ball nose, T3 3 mm flat end mill.\n"));
    assert!(file.contains("Plain GRBL refuses M6"));
    for n in [2, 3] {
        assert!(
            file.contains(&format!(
                "M5\nG4 P5\nG0 Z20\nG0 X0 Y0\n(Set Z again for T{n} before resuming)\nT{n} M6\nG17 G21 G90 G94 G54\nG0 Z5\nM3 S12000\nG4 P2\n"
            )),
            "{file}"
        );
    }
    let changes: Vec<&str> = file.lines().filter(|l| l.ends_with(" M6")).collect();
    assert_eq!(changes, ["T2 M6", "T3 M6"]);
    assert!(!file.contains("G4 P0.1"));
    assert!(file.ends_with("M5\nG0 X0 Y0\n"));
}

