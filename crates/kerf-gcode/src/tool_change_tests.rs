#[test]
fn bit_names_cannot_break_out_of_a_comment() {
    let job = job(vec![
        profile(Some(bit(1, "6 mm", 6.0)), 5.0),
        profile(Some(bit(2, "bad (name)\nM3 S1 ; x", 1.0)), 5.0),
    ]);
    let program = generate(&square(), &job).unwrap();
    for text in [
        program.text.clone(),
        program.with_m6().unwrap(),
        program.part_file(1).unwrap(),
    ] {
        assert!(!text.lines().any(|l| l.starts_with("M3 S1 ")), "{text}");
        assert!(
            text.contains("T2 (bad name M3 S1 x)") || text.contains("T2 bad name M3 S1 x."),
            "{text}"
        );
    }
}

