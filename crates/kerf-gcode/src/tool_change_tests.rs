#[test]
fn splitting_compares_tool_numbers_not_diameters() {
    // Two bits of the same size, a flat and a ball nose, are two bits.
    let mut ball = bit(2, "1/8\" ball nose", 3.175);
    ball.shape = "Ball nose".into();
    let job = job(vec![
        profile(Some(bit(1, "1/8\" flat end mill", 3.175)), 5.0),
        profile(Some(ball.clone()), 5.0),
        profile(Some(ball), 5.0),
        profile(Some(bit(1, "1/8\" flat end mill", 3.175)), 5.0),
    ]);
    let program = generate(&square(), &job).unwrap();
    let numbers: Vec<_> = program
        .parts
        .iter()
        .map(|p| p.tool.as_ref().unwrap().number)
        .collect();
    assert_eq!(numbers, [1, 2, 1]);
    assert_eq!(
        program
            .parts
            .iter()
            .map(|p| p.operations.clone())
            .collect::<Vec<_>>(),
        [0..1, 1..3, 3..4]
    );
}

