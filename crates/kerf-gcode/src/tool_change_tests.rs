//! Tests that pin the G-code of jobs that change bits.

use super::*;
use crate::generate::generate;
use crate::geometry::Artwork;
use crate::job::{Machine, OperationKind, Origin, ToolChange};

fn machine(kind: MachineKind) -> Machine {
    Machine {
        kind,
        bed_width: 100.0,
        bed_height: 100.0,
        max_power_s: 1000.0,
        travel_feed: 6000.0,
        origin: Origin::FrontLeft,
        start_gcode: String::new(),
        end_gcode: String::new(),
        tool_change: ToolChange::default(),
    }
}

fn square() -> Artwork {
    Artwork::from_svg(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="10mm" height="10mm" viewBox="0 0 10 10"><path d="M0 0H10V10H0Z" fill="#000000"/></svg>"##,
        0.05,
    )
    .unwrap()
}

fn bit(number: u32, name: &str, diameter: f64) -> ToolRef {
    ToolRef {
        number,
        name: name.into(),
        diameter,
        shape: "Flat end mill".into(),
    }
}

fn profile(tool: Option<ToolRef>, safe_z: f64) -> Operation {
    Operation {
        color: None,
        kind: OperationKind::CncProfile {
            depth: 1.0,
            depth_per_pass: 1.0,
            plunge_feed: 200.0,
            safe_z,
            spindle_rpm: 12000.0,
        },
        feed: 800.0,
        power: 0.0,
        passes: 1,
        tool,
    }
}

fn job(operations: Vec<Operation>) -> Job {
    Job {
        machine: machine(MachineKind::Cnc),
        offset: [20.0, 30.0],
        operations,
        material_thickness: None,
        cuts_parts: false,
    }
}

fn two_bits() -> Job {
    job(vec![
        profile(Some(bit(1, "6 mm flat end mill", 6.0)), 5.0),
        profile(Some(bit(2, "1 mm tapered ball nose", 1.0)), 5.0),
    ])
}

/// Program lines without comments.
fn code(text: &str) -> Vec<&str> {
    text.lines().filter(|l| !l.starts_with(';')).collect()
}

const VERSION: &str = env!("CARGO_PKG_VERSION");

/// One profile of the square, as every router job has always been written.
fn one_profile() -> String {
    format!(
        "; Generated by Kerf {VERSION}\nG21\nG90\nG0 Z5\nM3 S12000\nG4 P2\nG0 X20 Y70\nG1 Z-1 F200\nG1 X30 Y70 F800\nG1 X30 Y60\nG1 X20 Y60\nG1 X20 Y70\nG0 Z5\nM5\nG0 X0 Y0\n"
    )
}

#[test]
fn a_job_with_one_bit_is_unchanged() {
    assert_eq!(
        generate(&square(), &job(vec![profile(None, 5.0)]))
            .unwrap()
            .text,
        one_profile()
    );
    // With the bit named, and with the bit-change settings changed, the
    // text is the same to the byte.
    let one = bit(1, "1/8\" flat end mill", 3.175);
    let named = job(vec![profile(Some(one.clone()), 5.0)]);
    let mut changed = named.clone();
    changed.machine.tool_change.lift = 40.0;
    changed.machine.tool_change.spin_down = 9.0;
    changed.machine.tool_change.place = ChangePlace::Machine {
        position: [-1.0, -1.0, -1.0],
    };
    for job in [named, changed] {
        let program = generate(&square(), &job).unwrap();
        assert_eq!(program.text, one_profile());
        assert_eq!(program.parts.len(), 1);
        assert_eq!(program.part_streams(), [program.text.as_str()]);
        assert_eq!(program.part_file(0).unwrap(), program.text);
        assert_eq!(program.with_m6().unwrap(), program.text);
        assert!(!program.needs_homing && !program.atc && program.change_lift.is_none());
    }
    // Two operations with the same bit: still one part, written as before.
    let plain = job(vec![profile(None, 5.0), profile(None, 5.0)]);
    let same = bit(1, "1/8\" flat end mill", 3.175);
    let named = job(vec![
        profile(Some(same.clone()), 5.0),
        profile(Some(same), 5.0),
    ]);
    let plain = generate(&square(), &plain).unwrap();
    let named = generate(&square(), &named).unwrap();
    assert_eq!(named.text, plain.text);
    assert_eq!(named.parts.len(), 1);
}

#[test]
fn a_vendor_m6_at_the_end_of_a_laser_job_is_left_alone() {
    // The WeCreat laser's own start and end lines, its M6 among them, are
    // not a bit change, whatever the bit-change settings say.
    let mut job = Job {
        machine: Machine {
            origin: Origin::BackLeft,
            start_gcode: "M14S1\nM15S1\nM16".into(),
            end_gcode: "M6".into(),
            ..machine(MachineKind::Laser)
        },
        offset: [20.0, 30.0],
        operations: vec![Operation {
            color: None,
            kind: OperationKind::LaserCut,
            feed: 600.0,
            power: 50.0,
            passes: 1,
            tool: None,
        }],
        material_thickness: None,
        cuts_parts: false,
    };
    let expected = format!(
        "; Generated by Kerf {VERSION}\nM14S1\nM15S1\nM16\nG21\nG90\nM4 S0\nG0 X20 Y30 S0\nG1 X30 Y30 S500 F600\nG1 X30 Y40\nG1 X20 Y40\nG1 X20 Y30\nM5\nG0 X0 Y0\nM6\n"
    );
    assert_eq!(generate(&square(), &job).unwrap().text, expected);
    job.machine.tool_change.mode = ChangeMode::Atc;
    job.operations[0].tool = Some(bit(3, "nothing", 1.0));
    let program = generate(&square(), &job).unwrap();
    assert_eq!(program.text, expected);
    assert_eq!(program.parts.len(), 1);
    assert!(!program.atc);
    assert_eq!(program.with_m6().unwrap(), expected);
}

#[test]
fn a_bit_change_turns_the_spindle_off_then_lifts_then_moves() {
    let program = generate(&square(), &two_bits()).unwrap();
    let lines: Vec<&str> = program.text.lines().collect();
    let at = lines
        .iter()
        .position(|l| l.starts_with("; Bit change 1 of 1"))
        .unwrap();
    assert_eq!(
        lines[at..at + 6],
        [
            "; Bit change 1 of 1: fit T2 (1 mm tapered ball nose), then set Z again",
            "M5",
            "G4 P5",
            "G0 Z20",
            "G0 X0 Y0",
            "G4 P0.1",
        ]
    );
    // The part Kerf's sender streams ends there.
    let first = program.part_stream(0).unwrap();
    assert!(first.ends_with("G0 Z20\nG0 X0 Y0\nG4 P0.1\n"), "{first}");
    assert_eq!(program.change_lift, Some(20.0));
    // The parts' streams are the whole text, in order.
    assert_eq!(program.part_streams().concat(), program.text);
    let part = &program.parts[1];
    assert_eq!(
        program
            .text
            .lines()
            .skip(part.first_line)
            .take(part.line_count)
            .collect::<Vec<_>>(),
        program.part_stream(1).unwrap().lines().collect::<Vec<_>>()
    );
}

