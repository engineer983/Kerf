#[test]
fn atc_next_operation_travels_after_m6() {
    // Both bits work the same square, so the second starts where the first
    // began; the changer may have moved the head, so it travels there again.
    let mut job = two_bits();
    job.machine.tool_change.mode = ChangeMode::Atc;
    let program = generate(&square(), &job).unwrap();
    let lines = code(&program.text);
    let at = lines.iter().position(|l| *l == "T2 M6").unwrap();
    assert_eq!(
        lines[at + 1..at + 6],
        ["G0 Z5", "M3 S12000", "G4 P2", "G0 X20 Y70", "G1 Z-1 F200"]
    );
    // And after the first bit is loaded, even from the origin.
    job.machine.origin = Origin::BackLeft;
    job.offset = [0.0, 0.0];
    let program = generate(&square(), &job).unwrap();
    let lines = code(&program.text);
    let at = lines.iter().position(|l| *l == "T1 M6").unwrap();
    assert_eq!(
        lines[at + 1..at + 6],
        ["G0 Z5", "M3 S12000", "G4 P2", "G0 X0 Y0", "G1 Z-1 F200"]
    );
}

