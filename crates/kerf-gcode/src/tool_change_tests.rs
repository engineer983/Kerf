#[test]
fn no_part_writes_g49() {
    let mut job = two_bits();
    let mut texts = Vec::new();
    let program = generate(&square(), &job).unwrap();
    texts.push(program.text.clone());
    texts.push(program.with_m6().unwrap());
    texts.extend((0..2).map(|i| program.part_file(i).unwrap()));
    job.machine.tool_change.mode = ChangeMode::Atc;
    texts.push(generate(&square(), &job).unwrap().text);
    for text in texts {
        assert!(!text.contains("G49"), "{text}");
        assert!(!text.contains("G43"), "{text}");
    }
}

#[test]
fn the_next_part_starts_the_spindle_again_with_a_dwell() {
    let program = generate(&square(), &two_bits()).unwrap();
    let first = code(program.part_stream(0).unwrap());
    let off = first.iter().rposition(|l| *l == "M5").unwrap();
    assert!(!first[off..].iter().any(|l| l.starts_with("M3")));
    let second = code(program.part_stream(1).unwrap());
    assert_eq!(
        second[..4],
        ["G17 G21 G90 G94 G54", "G0 Z5", "M3 S12000", "G4 P2"]
    );
    assert_eq!(second[second.len() - 2..], ["M5", "G0 X0 Y0"]);
}

#[test]
fn machine_change_place_next_part_travels_before_plunging() {
    // Both bits work the same square, so part 2 starts where part 1 began.
    // After the change in machine coordinates the head is somewhere else,
    // so part 2 must still travel there before it plunges.
    let mut job = two_bits();
    job.machine.tool_change.place = ChangePlace::Machine {
        position: [-10.0, -20.5, -2.0],
    };
    let program = generate(&square(), &job).unwrap();
    let second = code(program.part_stream(1).unwrap());
    assert_eq!(
        second[..6],
        [
            "G17 G21 G90 G94 G54",
            "G0 Z5",
            "M3 S12000",
            "G4 P2",
            "G0 X20 Y70",
            "G1 Z-1 F200"
        ]
    );
    let file = program.part_file(1).unwrap();
    let lines = code(&file);
    let travel = lines.iter().position(|l| *l == "G0 X20 Y70").unwrap();
    let plunge = lines.iter().position(|l| l.starts_with("G1 Z")).unwrap();
    assert!(travel < plunge, "{file}");
    assert_eq!(program.change_clearance, Some(20.0));
}

#[test]
fn a_part_starting_at_the_origin_still_says_where_it_starts() {
    // Over the work zero the head is already at X0 Y0, and the next part's
    // first point is X0 Y0 too: the travel is written all the same.
    let mut job = two_bits();
    job.machine.origin = Origin::BackLeft;
    job.offset = [0.0, 0.0];
    let program = generate(&square(), &job).unwrap();
    let second = code(program.part_stream(1).unwrap());
    assert_eq!(
        second[..6],
        [
            "G17 G21 G90 G94 G54",
            "G0 Z5",
            "M3 S12000",
            "G4 P2",
            "G0 X0 Y0",
            "G1 Z-1 F200"
        ]
    );
}

#[test]
fn machine_change_place_raises_z_before_moving_across() {
    let mut job = two_bits();
    job.machine.tool_change.place = ChangePlace::Machine {
        position: [-10.0, -20.5, -2.0],
    };
    let program = generate(&square(), &job).unwrap();
    let first = code(program.part_stream(0).unwrap());
    assert_eq!(
        first[first.len() - 5..],
        ["M5", "G4 P5", "G53 G0 Z-2", "G53 G0 X-10 Y-20.5", "G4 P0.1"]
    );
    assert!(program.needs_homing);
    assert_eq!(program.machine_moves, [[-10.0, -20.5, -2.0]]);
    assert_eq!(program.change_lift, None);
    let m6 = program.with_m6().unwrap();
    assert!(
        m6.contains("G4 P5\nG53 G0 Z-2\nG53 G0 X-10 Y-20.5\n(Set Z again for T2"),
        "{m6}"
    );
}

