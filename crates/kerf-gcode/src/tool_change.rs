//! Jobs that change bits part way through.
//!
//! A router job whose operations use different bits is split into parts, one
//! per run of operations with the same tool number. Kerf's own sender streams
//! one part, waits with the machine idle while the person changes the bit and
//! sets Z again, then streams the next. Each part but the last ends with the
//! change block: the spindle off, a wait for it to stop, the bit raised, a
//! move to the change place, and a short dwell that is only answered once the
//! machine has stopped.
//!
//! For other senders the same parts are saved as one file per bit, or as one
//! file with `M6` at each change. On an automatic tool changer (grblHAL) the
//! job is one stream with `T<n> M6` at each change.
//!
//! A job with one bit is written exactly as before any of this existed.

use std::ops::Range;

use serde::Serialize;

use crate::generate::{num, Program, Writer};
use crate::job::{ChangeMode, ChangePlace, Job, MachineKind, Operation, ToolRef};

/// What each part of a multi-bit job opens with. Never `G49`: an automatic
/// changer's tool length offset is left as the controller set it.
pub(crate) const PART_HEADER: &str = "G17 G21 G90 G94 G54";
/// Ends each part before a change. A dwell is only answered once the
/// planner has emptied, so its `ok` means the machine has stopped.
pub(crate) const END_OF_PART: &str = "G4 P0.1";
/// Back to the origin, written in full even when already there.
const TO_ORIGIN: &str = "G0 X0 Y0";

/// One part of a program: the operations cut with one bit.
#[derive(Debug, Clone, PartialEq, Serialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct ProgramPart {
    pub tool: Option<ToolRef>,
    /// Which operations, in the order the job runs them.
    pub operations: Range<usize>,
    /// Lines of the program's text this part covers, for progress display.
    pub first_line: usize,
    pub line_count: usize,
    /// Byte range in the program's text that Kerf's sender streams.
    #[serde(skip)]
    pub(crate) stream: Range<usize>,
    /// Byte range of the operations alone, for the saved files.
    #[serde(skip)]
    pub(crate) body: Range<usize>,
}

/// What the saved files are built from, besides the parts' bodies.
#[derive(Debug, Clone, PartialEq, Default)]
pub(crate) struct Layout {
    /// The `; Generated by Kerf` line and the machine's start G-code.
    pub(crate) header: String,
    /// The machine's own end G-code, as written at the job's end.
    pub(crate) end: String,
    pub(crate) spin_down: f64,
    pub(crate) lift: f64,
    /// The moves at each change: up, then to the change place.
    pub(crate) change_moves: Vec<String>,
}

/// How a job is laid out, worked out before it is written.
pub(crate) struct Plan {
    /// Where each part starts, as indexes into the running order. Empty
    /// for a job with no changes.
    pub(crate) starts: Vec<usize>,
    pub(crate) atc: bool,
    pub(crate) lift: f64,
    pub(crate) spin_down: f64,
    pub(crate) place: ChangePlace,
}

impl Plan {
    /// `order` is the operations in the order they run.
    pub(crate) fn new(job: &Job, order: &[&Operation]) -> Self {
        let change = job.machine.tool_change;
        let numbers: Vec<Option<u32>> = order
            .iter()
            .map(|o| o.tool.as_ref().map(|t| t.number))
            .collect();
        let by_number = job.machine.kind == MachineKind::Cnc
            && !numbers.is_empty()
            && order.iter().all(|o| o.kind.is_router() && o.tool.is_some());
        let mut starts = Vec::new();
        if by_number {
            for i in 1..numbers.len() {
                if numbers[i] != numbers[i - 1] {
                    starts.push(i);
                }
            }
        }
        let highest_safe = order
            .iter()
            .filter_map(|o| o.kind.safe_z())
            .fold(0.0, f64::max);
        Self {
            starts,
            atc: by_number && change.mode == ChangeMode::Atc,
            lift: change.lift.max(highest_safe),
            spin_down: change.spin_down,
            place: change.place,
        }
    }

    /// Whether the job is written as before: one bit, changed by hand.
    pub(crate) fn plain(&self) -> bool {
        self.starts.is_empty() && !self.atc
    }

    /// Kerf's sender streams parts separately: bits changed by hand.
    pub(crate) fn split(&self) -> bool {
        !self.starts.is_empty() && !self.atc
    }
}

/// A bit's name made safe to put in a comment: one line, no brackets.
pub(crate) fn describe(tool: &ToolRef) -> String {
    tool.name
        .chars()
        .map(|c| match c {
            '(' | ')' | ';' => ' ',
            c if c.is_control() => ' ',
            c => c,
        })
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

/// `T2 (1 mm tapered ball nose)`, or `the next bit` if it has no name.
pub(crate) fn fit(tool: Option<&ToolRef>) -> String {
    match tool {
        Some(tool) => format!("T{} ({})", tool.number, describe(tool)),
        None => "the next bit".into(),
    }
}

/// The end of a part whose next bit is changed by hand: the spindle off
/// before anything moves, a wait for it to stop, Z up first, then across to
/// the change place, and the dwell that marks the end. Returns the two
/// moves, for the single file with `M6`.
pub(crate) fn write_change(
    w: &mut Writer,
    plan: &Plan,
    change: usize,
    of: usize,
    next: Option<&ToolRef>,
) -> String {
    w.line(&format!(
        "; Bit change {change} of {of}: fit {}, then set Z again",
        fit(next)
    ));
    w.line("M5");
    w.line(&format!("G4 P{}", num(plan.spin_down)));
    w.seconds += plan.spin_down;
    let moves = w.written();
    match plan.place {
        ChangePlace::OverWorkZero => {
            w.z_move(plan.lift, None);
            w.travel_to_origin();
        }
        ChangePlace::Machine {
            position: [x, y, z],
        } => {
            w.line(&format!("G53 G0 Z{}", num(z)));
            w.line(&format!("G53 G0 X{} Y{}", num(x), num(y)));
        }
    }
    let moves = w.written_since(moves).to_owned();
    w.line(END_OF_PART);
    moves
}

/// A change made by an automatic tool changer: the spindle off and stopped,
/// the bit raised, then the controller's own `T<n> M6`. The next
/// operation's `M3` and dwell follow.
pub(crate) fn write_atc_change(w: &mut Writer, plan: &Plan, next: Option<&ToolRef>) {
    let number = next.map_or(0, |t| t.number);
    w.line(&format!("; Bit change: {}", fit(next)));
    w.line("M5");
    w.line(&format!("G4 P{}", num(plan.spin_down)));
    w.seconds += plan.spin_down;
    w.z_move(plan.lift, None);
    w.line(&format!("T{number} M6"));
    // The changer's macro may move the head anywhere: travel before plunging.
    w.force_travel = true;
}

impl Program {
    /// The text Kerf's sender streams for part `i`.
    pub fn part_stream(&self, i: usize) -> Option<&str> {
        self.parts.get(i).map(|p| &self.text[p.stream.clone()])
    }

    /// The text of each part Kerf's sender streams, in order.
    pub fn part_streams(&self) -> Vec<&str> {
        (0..self.parts.len())
            .filter_map(|i| self.part_stream(i))
            .collect()
    }

    /// A file for part `i` alone, for any sender: it starts as a whole job
    /// does, and ends with the spindle off, the bit raised and the head back
    /// at the origin. A job with no changes has one part, its whole text.
    pub fn part_file(&self, i: usize) -> Result<String, String> {
        let Some(part) = self.parts.get(i) else {
            return Err(format!("This job has no part {}.", i + 1));
        };
        if self.parts.len() == 1 {
            return Ok(self.text.clone());
        }
        let layout = &self.layout;
        let mut out = String::new();
        let mut line = |text: &str| {
            out.push_str(text);
            out.push('\n');
        };
        for header in layout.header.lines() {
            line(header);
        }
        line(&format!(
            "; Part {} of {}, with {}.",
            i + 1,
            self.parts.len(),
            fit(part.tool.as_ref())
        ));
        if i > 0 {
            let tool = part.tool.as_ref();
            line(&match tool {
                Some(tool) => format!(
                    "; Fit T{} ({}) and set Z before running this file.",
                    tool.number,
                    describe(tool)
                ),
                None => "; Fit the bit and set Z before running this file.".into(),
            });
        }
        line(PART_HEADER);
        out.push_str(&self.text[part.body.clone()]);
        let mut line = |text: &str| {
            out.push_str(text);
            out.push('\n');
        };
        line("M5");
        let last = i + 1 == self.parts.len();
        if !last {
            line(&format!("G4 P{}", num(layout.spin_down)));
            line(&format!("G0 Z{}", num(layout.lift)));
        }
        line(TO_ORIGIN);
        for end in layout.end.lines() {
            line(end);
        }
        if !last {
            line(&format!(
                "; Next: fit {}, set Z again, then run part {}.",
                fit(self.parts[i + 1].tool.as_ref()),
                i + 2
            ));
        }
        Ok(out)
    }

    /// The whole job as one file with `M6` at each change, for senders that
    /// stop for a tool change and let the person set Z again.
    pub fn with_m6(&self) -> Result<String, String> {
        if self.parts.len() < 2 {
            return Ok(self.text.clone());
        }
        let layout = &self.layout;
        let mut out = String::new();
        let line = |out: &mut String, text: &str| {
            out.push_str(text);
            out.push('\n');
        };
        let mut lines = layout.header.lines();
        if let Some(first) = lines.next() {
            line(&mut out, first);
        }
        let bits: Vec<String> = self
            .parts
            .iter()
            .map(|p| match &p.tool {
                Some(tool) => format!("T{} {}", tool.number, describe(tool)),
                None => "a bit".into(),
            })
            .collect();
        line(
            &mut out,
            &format!(
                "; This job changes bits {} time{}: {}.",
                self.parts.len() - 1,
                if self.parts.len() == 2 { "" } else { "s" },
                bits.join(", ")
            ),
        );
        line(&mut out, "; Plain GRBL refuses M6. Use this file only with a sender that stops for the bit change and lets you set Z again.");
        for rest in lines {
            line(&mut out, rest);
        }
        for (i, part) in self.parts.iter().enumerate() {
            if i > 0 {
                let number = part.tool.as_ref().map_or(0, |t| t.number);
                line(&mut out, "M5");
                line(&mut out, &format!("G4 P{}", num(layout.spin_down)));
                if let Some(moves) = layout.change_moves.get(i - 1) {
                    out.push_str(moves);
                }
                line(
                    &mut out,
                    &format!("(Set Z again for T{number} before resuming)"),
                );
                line(&mut out, &format!("T{number} M6"));
            }
            line(&mut out, PART_HEADER);
            out.push_str(&self.text[part.body.clone()]);
        }
        line(&mut out, "M5");
        line(&mut out, TO_ORIGIN);
        for end in layout.end.lines() {
            line(&mut out, end);
        }
        Ok(out)
    }

    /// Moves what is only needed to send or save the program into a copy,
    /// leaving this one with what the interface is shown.
    pub fn split_off_text(&mut self) -> Program {
        Program {
            text: std::mem::take(&mut self.text),
            layout: std::mem::take(&mut self.layout),
            line_count: self.line_count,
            bounds: self.bounds,
            seconds: self.seconds,
            parts: self.parts.clone(),
            needs_homing: self.needs_homing,
            atc: self.atc,
            change_lift: self.change_lift,
            machine_moves: self.machine_moves.clone(),
            change_clearance: self.change_clearance,
            ..Program::default()
        }
    }
}

